// LobbyForge desktop shell — connect-to-instance controller.
//
// The shell shows a connect card; once a valid instance URL is entered, it
// navigates the Tauri webview directly to the instance URL. This avoids the
// iframe/CSP/X-Frame-Options conflict — the webview is a top-level navigation,
// not a framed embed. The Rust side persists the URL and drives global PTT.
//
// The tray's "Switch instance…" (Rust `leave_instance`) forgets the instance
// and navigates the window back to this local connect screen.

const { invoke } = window.__TAURI__?.core ?? {};

// ── Language ─────────────────────────────────────────────────────────────
// locales.js (generated by `pnpm i18n:sync` from apps/web/messages/*/
// desktop.json) holds every language the web app ships. Pick the best
// match for the system's languages: exact tag, then the base language,
// then English. The markup keeps English inline, so a missing table still
// reads fine.
const LOCALES = window.__LF_SHELL_LOCALES ?? {};

function pickLocale(wanted) {
  const codes = Object.keys(LOCALES);
  for (const tag of wanted) {
    const exact = codes.find((code) => code.toLowerCase() === String(tag).toLowerCase());
    if (exact) return exact;
    const base = String(tag).split('-')[0].toLowerCase();
    const partial = codes.find((code) => code.toLowerCase() === base || code.toLowerCase().split('-')[0] === base);
    if (partial) return partial;
  }
  return LOCALES.en ? 'en' : codes[0];
}

const locale = pickLocale(navigator.languages?.length ? navigator.languages : [navigator.language]);
const table = (locale && LOCALES[locale]) || { dir: 'ltr', strings: {} };

function t(key, fallback) {
  return table.strings[key] ?? LOCALES.en?.strings[key] ?? fallback ?? key;
}

if (locale) {
  document.documentElement.lang = locale;
  document.documentElement.dir = table.dir;
}
for (const el of document.querySelectorAll('[data-i18n]')) {
  el.textContent = t(el.dataset.i18n, el.textContent.trim());
}

// The tray is built in Rust; hand it the labels in this language (it keeps
// them for the next launch). Runs before any navigation to an instance.
invoke?.('set_tray_labels', {
  show: t('desktop.tray.show'),
  quit: t('desktop.tray.quit'),
  switchInstance: t('desktop.tray.switchInstance'),
  globalPtt: t('desktop.tray.globalPtt'),
}).catch(() => {});

// connect_instance answers a stable code when it refuses an address.
const CONNECT_ERRORS = {
  invalid_url: 'desktop.error.invalidUrl',
  https_required: 'desktop.error.httpsRequired',
  no_extras: 'desktop.error.noExtras',
  origin_only: 'desktop.error.originOnly',
};

const connectForm = document.getElementById('connect-form');
const urlInput = document.getElementById('instance-url');
const connectBtn = document.getElementById('connect-btn');
const errorMsg = document.getElementById('error-msg');

connectForm.addEventListener('submit', async (e) => {
  e.preventDefault();
  errorMsg.textContent = '';
  const raw = urlInput.value.trim();
  if (!raw) return;
  connectBtn.disabled = true;
  connectBtn.textContent = t('desktop.connect.connecting');
  try {
    // The Rust side validates + persists the URL, then calls
    // window.__lobbyforgeNavigate(url) which does a top-level navigation.
    await invoke('connect_instance', { rawUrl: raw });
  } catch (err) {
    const code = String(err?.message ?? err ?? '');
    if (!CONNECT_ERRORS[code]) console.error('[shell] connect failed:', code);
    errorMsg.textContent = t(CONNECT_ERRORS[code] ?? 'desktop.error.failed');
    connectBtn.disabled = false;
    connectBtn.textContent = t('desktop.connect.button');
  }
});

/**
 * Navigate the webview to an instance URL (or back to the connect screen).
 * Called by the Rust side via `window.__lobbyforgeNavigate(url | null)`.
 *
 * Using window.location.href for a top-level navigation instead of an iframe.
 * This respects the instance's X-Frame-Options: DENY and CSP frame-ancestors.
 * The Tauri webview acts as a browser tab — it navigates to the remote URL.
 */
window.__lobbyforgeNavigate = function (url) {
  if (url) {
    // Top-level navigation — the webview becomes the instance page.
    window.location.href = url;
  }
  // When null (disconnect), the Rust side should navigate back to the
  // local connect screen via tauri webview URL.
};

// Listen for push-to-talk events forwarded from the global shortcut.
const { listen } = window.__TAURI__?.event ?? {};
if (listen) {
  listen('lobbyforge://ptt', (event) => {
    const pressed = !!(event?.payload?.pressed);
    // Forward to the instance page via postMessage (same-origin after navigation).
    window.postMessage({ type: 'lobbyforge:ptt', pressed }, '*');
  });
}
